// This fixed purpose borrows the original offline signing custody and output
// lifetime. Neither caller-supplied X.509 fields nor a generic signer cross it.
func admitNodeCertificate(raw, signed []byte, pin string) (*networkSigning, error) {
	var plan struct {
		Schema    string          `json:"schema"`
		Reference string          `json:"reference_time"`
		Record    json.RawMessage `json:"record"`
	}
	if preparationObject(raw, &plan, "schema", "reference_time", "record") != nil || plan.Schema != "ardents-node-certificate-plan-v1" {
		return nil, errNetworkSigning
	}
	reference, err := admissionTime(plan.Reference)
	if err != nil {
		return nil, errNetworkSigning
	}
	_, prepared, err := prepareNetworkPublic("prepare-initial-node-record", plan.Record)
	digest := sha256.Sum256(signed)
	if err != nil || pin != hex.EncodeToString(digest[:]) {
		return nil, errNetworkSigning
	}
	facts, err := epoch.VerifyInitialClosedRecord(prepared, signed)
	if err != nil || facts.Carrier != epoch.CarrierClosedTCP {
		return nil, errNetworkSigning
	}
	return &networkSigning{operation: "prepare-node-certificate", public: bytes.Clone(facts.PublicKey),
		networkSigningInterval: networkSigningInterval{reference: reference, from: facts.ValidFrom, until: facts.ValidUntil}}, nil
}

func (s *networkSigning) nodeCertificate(key ed25519.PrivateKey) ([]networkSignedArtifact, error) {
	return s.nodeCertificateWithRandom(key, rand.Reader)
}

// The reader seam isolates entropy failure; the production operation always
// supplies crypto/rand.Reader and accepts no caller-controlled randomness.
func (s *networkSigning) nodeCertificateWithRandom(key ed25519.PrivateKey, random io.Reader) ([]networkSignedArtifact, error) {
	serial, err := rand.Int(random, new(big.Int).Lsh(big.NewInt(1), 128))
	if err != nil {
		return nil, errors.Join(errNetworkSigning, err)
	}
	if serial.Sign() <= 0 || s.checkTime(time.Now()) != nil {
		return nil, errNetworkSigning
	}
	leaf := &x509.Certificate{SerialNumber: serial, NotBefore: s.from, NotAfter: s.until,
		KeyUsage:              x509.KeyUsageDigitalSignature,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth, x509.ExtKeyUsageClientAuth},
		BasicConstraintsValid: true}
	der, err := x509.CreateCertificate(random, leaf, leaf, s.public, key)
	if err != nil {
		return nil, errors.Join(errNetworkSigning, err)
	}
	if s.verifyNodeCertificate(der) != nil {
		return nil, errNetworkSigning
	}
	raw := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})
	if len(raw) == 0 {
		return nil, errNetworkSigning
	}
	return []networkSignedArtifact{{"node-certificate.pem", raw}}, nil
}

// Examine the actual generated bytes through the standard-library parser and
// signature verifier, independently of the template passed to CreateCertificate.
func (s *networkSigning) verifyNodeCertificate(der []byte) error {
	c, err := x509.ParseCertificate(der)
	if err != nil {
		return errNetworkSigning
	}
	public, ok := c.PublicKey.(ed25519.PublicKey)
	if !ok || !bytes.Equal(public, s.public) || c.SignatureAlgorithm != x509.PureEd25519 ||
		c.CheckSignature(c.SignatureAlgorithm, c.RawTBSCertificate, c.Signature) != nil ||
		!c.NotBefore.Equal(s.from) || !c.NotAfter.Equal(s.until) || c.SerialNumber.Sign() <= 0 || c.SerialNumber.BitLen() > 128 ||
		c.Version != 3 || c.IsCA || !c.BasicConstraintsValid || c.MaxPathLen != -1 ||
		c.KeyUsage != x509.KeyUsageDigitalSignature || len(c.ExtKeyUsage) != 2 ||
		c.ExtKeyUsage[0] != x509.ExtKeyUsageServerAuth || c.ExtKeyUsage[1] != x509.ExtKeyUsageClientAuth ||
		len(c.UnknownExtKeyUsage) != 0 || len(c.UnhandledCriticalExtensions) != 0 ||
		!bytes.Equal(c.RawSubject, []byte{0x30, 0}) || !bytes.Equal(c.RawIssuer, c.RawSubject) ||
		len(c.Extensions) != 3 {
		return errNetworkSigning
	}
	// Only key usage, extended key usage and basic constraints may be encoded.
	seen := make(map[string]bool, 3)
	for _, e := range c.Extensions {
		oid := e.Id.String()
		if seen[oid] || (oid != "2.5.29.15" && oid != "2.5.29.37" && oid != "2.5.29.19") {
			return errNetworkSigning
		}
		seen[oid] = true
	}
	return nil
}
